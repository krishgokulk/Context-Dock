// ClipboardHistoryEngine.swift
// Context-Dock
//
// The clipboard history itself: every copy recorded, kept, trimmed and forgotten.
//
// It used to live inside the old launcher view (issue #247, step 4a). That view is built at
// startup and never shown any more, but its pasteboard poll, its capture handler and its
// disk writes were what the Corner's clipboard board read — so deleting the view would have
// silently stopped the history. Moved here unchanged: the poll, the concealed-clip guard,
// de-duplication, the image sidecar, OCR, trimming, expiry and the debounced write.
//
// The board (`ClipboardPanelModel`) reads the same file and is told about each new clip.

import AppKit
import Combine
import CryptoKit
import Vision

@MainActor
final class ClipboardHistoryEngine {
    static let shared = ClipboardHistoryEngine()

    typealias Entry = LauncherView.ClipboardEntry

    /// Newest first.
    var history: [Entry] = []
    /// The pasteboard's `changeCount` last looked at, so a poll only acts on a new copy.
    var lastCheckedPasteboardCount = NSPasteboard.general.changeCount
    /// Set around a read DoraX makes through the pasteboard itself, so it is not recorded.
    var suppressImportUntilChangeCount: Int?

    private var monitorTimer: Timer?
    private var expiryTimer: Timer?
    private var saveTask: Task<Void, Never>?
    private var sinks = Set<AnyCancellable>()
    private var isStarted = false

    private init() {}

    /// Load the history and start recording. Once, at launch.
    func start() {
        guard !isStarted else { return }
        isStarted = true
        load()
        lastCheckedPasteboardCount = NSPasteboard.general.changeCount
        // The history is only trustworthy if it records every copy. Reading `changeCount`
        // is a couple of microseconds, so this polls whether or not anything is on screen.
        monitorTimer = Timer.scheduledTimer(withTimeInterval: 0.4, repeats: true) { _ in
            MainActor.assumeIsolated { ClipboardHistoryEngine.shared.checkPasteboard() }
        }
        monitorTimer?.tolerance = 0.1
        // Expiry, and a limit lowered in Settings, take effect within the minute.
        expiryTimer = Timer.scheduledTimer(withTimeInterval: 60, repeats: true) { _ in
            MainActor.assumeIsolated { ClipboardHistoryEngine.shared.trimToLimits() }
        }
        ClipboardIngestBus.shared.captures
            .sink { [weak self] in self?.handleCapture($0) }
            .store(in: &sinks)
        NotificationCenter.default.publisher(for: .clipboardEntriesRemovalRequested)
            .sink { [weak self] note in
                guard let raw = note.userInfo?["ids"] as? [String] else { return }
                self?.remove(ids: Set(raw.compactMap(UUID.init(uuidString:))))
            }
            .store(in: &sinks)
        // Never lose the tail of a debounced write.
        NotificationCenter.default.publisher(for: NSApplication.willTerminateNotification)
            .sink { [weak self] _ in self?.flushToDisk(waiting: true) }
            .store(in: &sinks)
    }

    // MARK: - Recording

    func checkPasteboard() {
        let pb = NSPasteboard.general
        let currentCount = pb.changeCount
        guard currentCount != lastCheckedPasteboardCount else { return }
        lastCheckedPasteboardCount = currentCount
        // The board's own paste or copy: already a clip, not a new one.
        if currentCount == ClipboardScopeService.ownWriteChangeCount { return }

        if let suppressed = suppressImportUntilChangeCount {
            if currentCount <= suppressed {
                if currentCount == suppressed {
                    suppressImportUntilChangeCount = nil
                }
                return
            }
            suppressImportUntilChangeCount = nil
        }

        // Password managers and other privacy-aware apps flag their clips; an
        // always-on history must never record those.
        guard !Self.isConcealed(pb) else { return }

        pruneExpired()
        _ = importCurrentPasteboard()
    }

    /// Honours the community `org.nspasteboard.*` markers (1Password, Bitwarden,
    /// KeePassXC, …) plus Apple's own concealed type.
    static func isConcealed(_ pb: NSPasteboard) -> Bool {
        let markers: Set<String> = [
            "org.nspasteboard.ConcealedType",
            "org.nspasteboard.TransientType",
            "org.nspasteboard.AutoGeneratedType",
            "com.agilebits.onepassword",
            "de.petermaurer.TransientPasteboardType",
        ]
        let types = (pb.types ?? []).map(\.rawValue)
        return types.contains { markers.contains($0) }
    }

    /// Clip produced by the app itself (Capture Text / Capture Area / Screenshot).
    /// Arrives with the real source app and the changeCount of its own pasteboard
    /// write, so the poll never re-imports it as an anonymous clip.
    func handleCapture(_ payload: ClipboardCapturePayload) {
        lastCheckedPasteboardCount = payload.pasteboardChangeCount
        let source = (name: payload.sourceAppName, bundleId: payload.sourceBundleId)
        switch payload.content {
        case .text(let text):
            add(text: text, filePaths: [], source: source, isScreenCapture: payload.isScreenCapture)
        case .image(let data, let savedFilePath):
            add(
                text: "",
                // The saved screenshot path rides along so Quick Look and drag-out use
                // the real file instead of a temp copy; the clip still renders as an image.
                filePaths: savedFilePath.map { [$0] } ?? [],
                imageData: data,
                source: source,
                isScreenCapture: payload.isScreenCapture)
        }
    }

    @discardableResult
    func importCurrentPasteboard() -> Bool {
        let pb = NSPasteboard.general

        if let fileURLs = pb.readObjects(forClasses: [NSURL.self], options: nil) as? [URL] {
            let paths = fileURLs.filter { $0.isFileURL }.map(\.path).filter { !$0.isEmpty }
            if !paths.isEmpty {
                add(text: paths.joined(separator: "\n"), filePaths: paths)
                return true
            }
        }

        if let image = NSImage(pasteboard: pb), let tiffData = image.tiffRepresentation {
            // Empty text — the entry IS the image (preview shows "Image", OCR fills ocrText).
            // A placeholder string here used to get pasted instead of the actual image.
            // Re-encode to PNG immediately: pasteboard TIFF is several times larger, and
            // this is the form that goes to disk, to Vision and back onto the pasteboard.
            add(
                text: "", filePaths: [],
                imageData: ClipboardImageStore.pngData(from: tiffData) ?? tiffData)
            return true
        }

        guard pb.pasteboardItems?.first?.types.contains(.string) == true,
            let text = pb.string(forType: .string)
        else { return false }
        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
        guard trimmed.count > 3 else { return false }

        add(text: trimmed, filePaths: [])
        return true
    }

    func add(
        text: String,
        filePaths: [String],
        imageData: Data? = nil,
        source: (name: String, bundleId: String)? = nil,
        isScreenCapture: Bool = false
    ) {
        let sourceApp = source ?? Self.sourceApp()
        let hash = Self.contentHash(text: text, filePaths: filePaths, imageData: imageData)
        let entry = Entry(
            text: text,
            timestamp: Date(),
            filePaths: filePaths,
            imageData: imageData,
            sourceAppName: sourceApp.name,
            sourceBundleId: sourceApp.bundleId,
            isScreenCapture: isScreenCapture,
            contentHash: hash
        )

        let removed = history.filter { $0.contentHash == hash }
        history.removeAll { $0.contentHash == hash }
        ClipboardImageStore.delete(fileNames: removed.compactMap(\.imageFileName))
        history.insert(entry, at: 0)
        if let imageData {
            persistImageBlob(entryID: entry.id, data: imageData)
            scheduleOCR(for: entry.id, imageData: imageData)
        }
        trimToLimits()
        save()

        // The board is a system-wide surface, so it is told about every copy. It orders
        // itself in without activating us.
        ClipboardPanelController.shared.didCopy(entry)
    }

    /// Identity of a clip's *content*, independent of when or where it was copied.
    static func contentHash(text: String, filePaths: [String], imageData: Data?) -> String {
        if let imageData {
            return "image:" + SHA256.hash(data: imageData).prefix(8)
                .map { String(format: "%02x", $0) }.joined()
        }
        if !filePaths.isEmpty { return "files:" + filePaths.joined(separator: "\n") }
        return "text:" + text
    }

    static func sourceApp() -> (name: String, bundleId: String) {
        let app = AppDelegate.shared?.previousFrontmostApp ?? NSWorkspace.shared.frontmostApplication
        return (app?.localizedName ?? "", app?.bundleIdentifier ?? "")
    }

    // MARK: - Removing

    /// The board asked to drop clips. It reads the same history this writes, and the image
    /// blobs live beside that file, so removal happens here where both are owned.
    func remove(ids: Set<UUID>) {
        guard !ids.isEmpty else { return }
        let doomed = history.filter { ids.contains($0.id) }
        guard !doomed.isEmpty else { return }
        history.removeAll { ids.contains($0.id) }
        ClipboardImageStore.delete(fileNames: doomed.compactMap(\.imageFileName))
        save()
    }

    func trimToLimits(save shouldSave: Bool = true) {
        let before = history.map(\.id)
        pruneExpired(save: false)
        let limit = AppSettings.shared.clipboardHistoryLimit
        if history.count > limit {
            let dropped = history.suffix(from: limit)
            ClipboardImageStore.delete(fileNames: dropped.compactMap(\.imageFileName))
            history = Array(history.prefix(limit))
        }
        releaseColdImageMemory()
        if shouldSave && before != history.map(\.id) {
            save()
        }
    }

    func pruneExpired(save shouldSave: Bool = true) {
        let retention = TimeInterval(max(1, AppSettings.shared.clipboardHistoryRetentionHours)) * 3600
        let cutoff = Date().addingTimeInterval(-retention)
        let expired = history.filter { $0.timestamp < cutoff }
        guard !expired.isEmpty else { return }
        ClipboardImageStore.delete(fileNames: expired.compactMap(\.imageFileName))
        history.removeAll { $0.timestamp < cutoff }
        if shouldSave { save() }
    }

    /// Only the newest few image clips keep their bytes resident; older ones fall back to
    /// the sidecar blob. Without this a 50-clip screenshot history sat permanently in RAM.
    private func releaseColdImageMemory(keepingNewest keep: Int = 4) {
        var seenImages = 0
        for index in history.indices where history[index].imageData != nil {
            seenImages += 1
            guard seenImages > keep, history[index].imageFileName != nil else { continue }
            history[index].imageData = nil
        }
    }

    // MARK: - Images and OCR

    /// Writes the clip's bytes to the sidecar store off the main thread, then records the
    /// file name so a later launch (or a memory-trimmed entry) can find them again.
    private func persistImageBlob(entryID: UUID, data: Data) {
        let fileName = "\(entryID.uuidString).png"
        Task.detached(priority: .utility) {
            guard ClipboardImageStore.write(data, fileName: fileName) else { return }
            await MainActor.run {
                let engine = ClipboardHistoryEngine.shared
                guard let index = engine.history.firstIndex(where: { $0.id == entryID }) else {
                    // Entry was trimmed while we were writing — don't leave the blob behind.
                    ClipboardImageStore.delete(fileNames: [fileName])
                    return
                }
                engine.history[index].imageFileName = fileName
                engine.save()
            }
        }
    }

    /// Full image bytes for a clip: in memory for recent clips, off the sidecar store for
    /// everything the history reloaded from disk.
    static func imageData(for entry: Entry) -> Data? {
        if let data = entry.imageData { return data }
        guard let fileName = entry.imageFileName else { return nil }
        return ClipboardImageStore.read(fileName: fileName)
    }

    private func scheduleOCR(for entryID: UUID, imageData: Data) {
        Task.detached(priority: .utility) {
            // One image at a time: a burst of screenshots used to start a Vision request
            // per clip and peg every core while the user was still typing.
            await ClipboardOCRQueue.shared.run {
                guard let nsImage = NSImage(data: imageData),
                    let cgImage = nsImage.cgImage(forProposedRect: nil, context: nil, hints: nil)
                else { return }
                let request = VNRecognizeTextRequest()
                request.recognitionLevel = .accurate
                request.usesLanguageCorrection = true
                let handler = VNImageRequestHandler(cgImage: cgImage, options: [:])
                do {
                    try handler.perform([request])
                    let text = (request.results ?? [])
                        .compactMap { $0.topCandidates(1).first?.string }
                        .joined(separator: "\n")
                        .trimmingCharacters(in: .whitespacesAndNewlines)
                    guard !text.isEmpty else { return }
                    await MainActor.run {
                        let engine = ClipboardHistoryEngine.shared
                        guard let index = engine.history.firstIndex(where: { $0.id == entryID })
                        else { return }
                        engine.history[index].ocrText = text
                        engine.save()
                    }
                } catch {
                    // OCR is best-effort; the clip still works without recognized text.
                }
            }
        }
    }

    // MARK: - Disk

    static var storeURL: URL { ClipboardPanelModel.defaultStoreURL }

    func load() {
        let url = Self.storeURL
        guard FileManager.default.fileExists(atPath: url.path),
            let data = try? Data(contentsOf: url),
            let entries = try? JSONDecoder().decode([Entry].self, from: data)
        else { return }
        var loaded = entries.sorted { $0.timestamp > $1.timestamp }
        // Backfill for histories written before content hashes / sidecar blobs existed.
        for index in loaded.indices where loaded[index].contentHash.isEmpty {
            loaded[index].contentHash = Self.contentHash(
                text: loaded[index].text,
                filePaths: loaded[index].filePaths,
                imageData: loaded[index].imageData)
        }
        history = loaded
        // Legacy entries still carry inline image bytes — move them to the sidecar store
        // once, then the JSON stays small forever.
        for entry in loaded where entry.imageFileName == nil {
            if let bytes = entry.imageData { persistImageBlob(entryID: entry.id, data: bytes) }
        }
        trimToLimits(save: false)
        save()
    }

    /// Debounced: a burst of copies (or a run of OCR completions) coalesces into one
    /// encode + one atomic write instead of one per change.
    func save() {
        saveTask?.cancel()
        saveTask = Task { @MainActor in
            try? await Task.sleep(nanoseconds: 600_000_000)
            guard !Task.isCancelled else { return }
            flushToDisk()
        }
    }

    /// `waiting`: at quit, write before returning — a detached write can lose the race.
    func flushToDisk(waiting: Bool = false) {
        saveTask?.cancel()
        saveTask = nil
        let entries = history
        let url = Self.storeURL
        let liveBlobs = Set(entries.compactMap(\.imageFileName))
        let write: @Sendable () -> Void = {
            do {
                try FileManager.default.createDirectory(
                    at: url.deletingLastPathComponent(), withIntermediateDirectories: true)
                let data = try JSONEncoder().encode(entries)
                try data.write(to: url, options: .atomic)
            } catch {}
            ClipboardImageStore.pruneOrphans(keeping: liveBlobs)
        }
        if waiting {
            write()
        } else {
            Task.detached(priority: .utility) { write() }
        }
    }
}
